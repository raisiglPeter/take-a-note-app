export type Json =
  | string
  | number
  | boolean
  | null
  | { [key: string]: Json | undefined }
  | Json[];

export interface Database {
  public: {
    Tables: {
      notes: {
        Row: {
          id: string; // UUID generated by Postgres
          user_id: string; // ID of the user who owns the note
          title: string; // Note title
          content: string | null; // Content (nullable if empty)
          created_at: string; // ISO Timestamp
        };
        Insert: {
          id?: string; // Optional when inserting (Postgres generates UUID automatically)
          user_id: string; // Required: must provide user ID
          title: string; // Required: must provide title
          content?: string | null; // Optional: can leave blank
          created_at?: string; // Optional: Postgres defaults to now()
        };
        Update: {
          id?: string; // Optional when updating
          user_id?: string; // Optional
          title?: string; // Optional (only include if changing title)
          content?: string | null; // Optional
          created_at?: string; // Optional
        };
      };
      habits: {
        Row: {
          id: string;
          user_id: string;
          title: string;
          progress_nodes: boolean[]; // Array of booleans [true, false, false]
          created_at: string;
        };
        Insert: {
          id?: string;
          user_id: string;
          title: string;
          progress_nodes?: boolean[];
          created_at?: string;
        };
        Update: {
          id?: string;
          user_id?: string;
          title?: string;
          progress_nodes?: boolean[];
          created_at?: string;
        };
      };
    };
  };
}

// Shortcut type helpers for clean imports in your components
export type Note = Database["public"]["Tables"]["notes"]["Row"];
export type InsertNote = Database["public"]["Tables"]["notes"]["Insert"];

export type Habit = Database["public"]["Tables"]["habits"]["Row"];
export type InsertHabit = Database["public"]["Tables"]["habits"]["Insert"];
